import { describe, it, expect, beforeEach, vi } from 'vitest';
import { screen } from '@testing-library/react';
import { Routes, Route } from 'react-router-dom';
import { renderWithProviders } from '../../test/renderWithProviders';
import ProfileBabyPage from './ProfileBabyPage';

window.HTMLElement.prototype.scrollIntoView = vi.fn();

const S = Object.fromEntries(
  ['asistente', 'assignment', 'volunteer', 'user', 'mother', 'baby', 'proveedor', 'sala', 'reporte',
    'generics', 'supply', 'dashboard', 'estadisticaAvanzada', 'toast', 'visita', 'horario', 'tarea']
    .map((k) => [`${k}Reducer`, {}]),
);

describe('ProfileBabyPage (smoke)', () => {
  beforeEach(() => {
    localStorage.clear();
    localStorage.setItem('token', 't');
    localStorage.setItem('voluntaria', JSON.stringify({ id: 1, nombre: 'Test', apellido: 'User', rol: 'coordinadora', idRol: 3 }));
  });

  it('renderiza el perfil del bebé sin crashear', () => {
    renderWithProviders(
      <Routes>
        <Route path="/bebe/perfil/:id" element={<ProfileBabyPage />} />
      </Routes>,
      { route: '/bebe/perfil/1', preloadedState: S },
    );
    expect(screen.getByText(/perfil del bebé/i)).toBeInTheDocument();
  });
});
